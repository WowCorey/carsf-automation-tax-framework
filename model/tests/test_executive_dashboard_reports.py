def test_ci_runs_executive_dashboard_runner_before_evidence_and_guardrails(repo_root) -> None:
    workflow = (repo_root / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")

    legislative_index = workflow.index("python scripts/run_legislative_architecture.py")
    dashboard_index = workflow.index("python scripts/run_executive_dashboard.py")
    evidence_index = workflow.index("python scripts/run_evidence_workflow.py")
    guardrail_index = workflow.index("python scripts/run_repo_guardrails.py")

    assert legislative_index < dashboard_index < evidence_index < guardrail_index
