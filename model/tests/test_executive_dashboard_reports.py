from __future__ import annotations

import json
import subprocess
import sys

from carsf.executive_dashboard import (
    EXECUTIVE_DASHBOARD_WARNING,
    find_forbidden_affirmative_dashboard_claims,
)


def test_executive_dashboard_report_generates_json_and_markdown(repo_root) -> None:
    reports_dir = repo_root / "tmp" / "test-executive-dashboard"
    completed = subprocess.run(
        [sys.executable, "scripts/run_executive_dashboard.py", "--reports-dir", str(reports_dir)],
        cwd=repo_root,
        check=False,
        capture_output=True,
        text=True,
    )

    assert completed.returncode == 0, completed.stderr
    assert (reports_dir / "executive_dashboard.md").exists()
    assert (reports_dir / "executive_dashboard.json").exists()


def test_executive_dashboard_report_includes_non_claim_language_and_false_flags(repo_root) -> None:
    reports_dir = repo_root / "tmp" / "test-executive-dashboard-nonclaims"
    subprocess.run(
        [sys.executable, "scripts/run_executive_dashboard.py", "--reports-dir", str(reports_dir)],
        cwd=repo_root,
        check=True,
    )
    markdown = (reports_dir / "executive_dashboard.md").read_text(encoding="utf-8")
    payload = json.loads((reports_dir / "executive_dashboard.json").read_text(encoding="utf-8"))

    assert EXECUTIVE_DASHBOARD_WARNING in markdown
    assert EXECUTIVE_DASHBOARD_WARNING in payload["metadata"]["non_claims"]
    for key in [
        "real_data_used",
        "readiness_score_created",
        "operational_readiness_claimed",
        "legal_sufficiency_claimed",
        "economic_validation_claimed",
        "firm_level_liability_logic_modified",
    ]:
        assert payload["metadata"][key] is False
        assert payload["summary"][key] is False


